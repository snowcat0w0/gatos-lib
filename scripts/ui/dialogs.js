/**
 * gatos-lib — DialogV2 helpers.
 *
 * All helpers wrap `foundry.applications.api.DialogV2.wait` with `rejectClose: false` and resolve `null` when
 * the dialog is cancelled or closed (confirm resolves `false`). Default button labels are Foundry core lang keys
 * ("Confirm", "Cancel", "Yes", "No") so they still read correctly when gatos-lib's own lang files are not
 * loaded; only the pick dialogs use `GATOSLIB.Pick` / `GATOSLIB.PickMax`, with a core fallback.
 *
 * DialogV2 facts relied on (client/applications/api/dialog.mjs):
 * - content is wrapped in `<form class="dialog-form">`, so `button.form` is the form;
 * - a button callback is `(event, button, dialog)` and a nullish return becomes the button's action string,
 *   which is why every callback here returns a boxed value;
 * - string content passes through foundry.utils.cleanHTML (inputs, data-* and img src survive);
 * - `render(event, dialog)` is attached as a "render" listener.
 *
 * Provenance: CT viewer.js:524,578,593,652,818,853, PP party-panel.js:603-763, HP hero-points.js:73-139,
 * HM module.js:193-231, VIT module.js:169-183 + spirit-of-many.js:132-186, LT drop.js:32-42 (PLAN §3).
 */
import { readForm, dialogRoot } from "./app.js";
import { esc } from "./dom.js";
import { renderTemplate } from "../core/compat.js";

/** Name of the inputs generated by pickList. */
const PICK_FIELD = "gatosPick";

const BOX = Symbol("gatos-lib.dialogResult");
const box = (value) => ({ [BOX]: true, value });
const unbox = (result) => (result && typeof result === "object" && result[BOX] ? result.value ?? null : null);

const DialogV2 = () => foundry.applications.api.DialogV2;
const loc = (s) => (s ? game.i18n.localize(String(s)) : "");
/** Library key when its lang file is loaded, otherwise a core key. */
const libKey = (key, fallback) => (game.i18n.has(key) ? key : fallback);
const asClasses = (c) => (Array.isArray(c) ? c : String(c ?? "").split(/\s+/)).filter(Boolean);
const isHTML = (s) => /<[a-z][\s\S]*>/i.test(String(s ?? ""));

/**
 * Open a DialogV2 whose buttons all return boxed values, and unbox the result.
 * @returns {Promise<*>}
 */
async function wait({ title = "", icon = "", content = "", width = 400, classes, position = {}, window: win = {}, render, buttons, ...rest }) {
  const result = await DialogV2().wait({
    ...rest,
    window: { title, icon, ...win },
    classes: ["gatos-dialog", ...asClasses(classes)],
    position: { width, ...position },
    content,
    render,
    rejectClose: false,
    buttons,
  });
  return unbox(result);
}

/**
 * @typedef DialogButton
 * @property {string} action
 * @property {string} [label]     Lang key or text (DialogV2 localizes it)
 * @property {string} [icon]
 * @property {boolean} [default]
 * @property {string} [class]
 * @property {boolean} [disabled]
 * @property {(button: HTMLButtonElement, dialog: DialogV2, event: Event) => *} [read]  Overrides ok.read
 * @property {(event: Event, button: HTMLButtonElement, dialog: DialogV2) => *} [callback]  Native DialogV2 callback;
 *           its return value is the result
 */

/**
 * Generic form dialog: the 41-site skeleton of "DialogV2 + read the form on OK".
 *
 * Result: OK → `ok.read(button)` (default readForm → plain object); an extra button without `callback` →
 * `{ action, data: read(button) }`; an extra button with `callback` → whatever it returns; cancel / close → null.
 * Pass `ok: false` to drop the OK button (e.g. two action buttons such as PP's damage / heal).
 *
 * @param {object} config
 * @param {string} [config.title]        Lang key or text
 * @param {string} [config.icon]         Window icon classes
 * @param {string|HTMLElement} [config.content]  HTML (a <div> without attributes when an element)
 * @param {string} [config.template]     Handlebars template rendered into content with `config.data`
 * @param {object} [config.data]
 * @param {number} [config.width=400]
 * @param {string|string[]} [config.classes]  Extra window classes (the library adds "gatos-dialog")
 * @param {(event: Event, dialog: DialogV2) => void} [config.render]  Live behaviour after render
 * @param {false|{action?: string, label?: string, icon?: string, default?: boolean,
 *   read?: (button: HTMLButtonElement, dialog: DialogV2, event: Event) => *,
 *   callback?: (event: Event, button: HTMLButtonElement, dialog: DialogV2) => *}} [config.ok]
 * @param {false|{action?: string, label?: string, icon?: string, default?: boolean}} [config.cancel]
 * @param {DialogButton[]} [config.buttons]  Extra buttons, placed between OK and Cancel
 * @returns {Promise<*>}
 */
export async function formDialog({
  title,
  icon,
  content = "",
  template,
  data,
  width = 400,
  classes,
  render,
  ok = {},
  cancel = {},
  buttons = [],
  ...rest
} = {}) {
  if (template) content = await renderTemplate(template, data ?? {});
  // Default reader takes only the button: readForm's second parameter is an options bag, not the dialog.
  const read = (ok && ok.read) || ((button) => readForm(button));
  // Note: DialogV2's `default` only sets autofocus. Enter inside an input submits the form through the FIRST
  // button in DOM order, i.e. OK (or the first extra button when ok === false), whatever `default` says.
  const anyDefault = buttons.some((b) => b.default);
  const list = [];

  if (ok !== false) {
    const { read: _r, callback, ...def } = ok ?? {};
    list.push({
      label: "Confirm",
      icon: "fa-solid fa-check",
      ...def,
      action: def.action ?? "ok",
      default: def.default ?? !anyDefault,
      callback: async (event, button, dialog) =>
        box(callback ? await callback(event, button, dialog) : await read(button, dialog, event)),
    });
  }

  for (const b of buttons) {
    const { read: own, callback, ...def } = b;
    list.push({
      ...def,
      label: def.label ?? def.action,
      callback: async (event, button, dialog) =>
        box(callback ? await callback(event, button, dialog) : { action: def.action, data: await (own ?? read)(button, dialog, event) }),
    });
  }

  if (cancel !== false) {
    list.push({
      label: "Cancel",
      icon: "fa-solid fa-xmark",
      ...(cancel ?? {}),
      action: cancel?.action ?? "cancel",
      callback: () => box(null),
    });
  }

  return wait({ ...rest, title, icon, content, width, classes, render, buttons: list });
}

/**
 * Yes / No question.  ported from CT viewer.js:524, BF buff-finder.js:540-548
 * @param {object} config
 * @param {string} [config.title]
 * @param {string} [config.icon]
 * @param {string} [config.content]  HTML; text without tags is wrapped in <p>
 * @param {object} [config.yes]      Overrides for the Yes button (label, icon, ...)
 * @param {object} [config.no]       Overrides for the No button
 * @param {boolean} [config.defaultYes=false]
 * @param {boolean} [config.skip=false]  Resolve true without asking (e.g. `event.shiftKey`)
 * @returns {Promise<boolean>}
 */
export async function confirm({ title, icon, content = "", yes = {}, no = {}, defaultYes = false, skip = false, width = 400, ...rest } = {}) {
  if (skip) return true;
  const result = await wait({
    ...rest,
    title,
    icon,
    width,
    content: isHTML(content) ? content : `<p>${content}</p>`,
    buttons: [
      { action: "yes", label: "Yes", icon: "fa-solid fa-check", default: defaultYes, ...yes, callback: () => box(true) },
      { action: "no", label: "No", icon: "fa-solid fa-xmark", default: !defaultYes, ...no, callback: () => box(false) },
    ],
  });
  return result === true;
}

/**
 * Ask for one line of text.  ported from CT viewer.js:578 (rename)
 * @param {object} config
 * @param {string} [config.title]
 * @param {string} [config.label]        Lang key or text
 * @param {string} [config.value]
 * @param {string} [config.placeholder]  Lang key or text
 * @param {string} [config.hint]         Lang key or text shown under the field
 * @param {boolean} [config.allowEmpty=false]  Resolve "" instead of null for an empty field
 * @param {object} [config.ok]           Overrides for the OK button
 * @returns {Promise<string|null>} trimmed text, or null
 */
export async function promptText({ title, icon, label = "", value = "", placeholder = "", hint = "", allowEmpty = false, ok = {}, ...rest } = {}) {
  const content = `<div class="form-group">
      ${label ? `<label>${esc(loc(label))}</label>` : ""}
      <div class="form-fields"><input type="text" name="value" value="${esc(value)}" placeholder="${esc(loc(placeholder))}" autofocus></div>
      ${hint ? `<p class="hint">${esc(loc(hint))}</p>` : ""}
    </div>`;
  const read = (button) => {
    const text = String((button.form ?? dialogRoot(button))?.querySelector("input[name=value]")?.value ?? "").trim();
    return text || allowEmpty ? text : null;
  };
  return formDialog({ ...rest, title, icon, content, ok: { ...ok, read } });
}

/**
 * Ask for a number.  ported from PP party-panel.js:603-647 (amount field)
 * @param {object} config
 * @param {string} [config.title]
 * @param {string} [config.label]
 * @param {number} [config.value]
 * @param {number} [config.min]
 * @param {number} [config.max]
 * @param {number|"any"} [config.step=1]
 * @param {string} [config.hint]
 * @param {object} [config.ok]
 * @returns {Promise<number|null>} the value clamped to min/max, or null when empty / cancelled
 */
export async function promptNumber({ title, icon, label = "", value = "", min, max, step = 1, hint = "", ok = {}, ...rest } = {}) {
  const attr = (name, v) => (v === undefined || v === null || v === "" ? "" : ` ${name}="${esc(v)}"`);
  const content = `<div class="form-group">
      ${label ? `<label>${esc(loc(label))}</label>` : ""}
      <div class="form-fields"><input type="number" name="value"${attr("value", value)}${attr("min", min)}${attr("max", max)}${attr("step", step)} autofocus></div>
      ${hint ? `<p class="hint">${esc(loc(hint))}</p>` : ""}
    </div>`;
  const read = (button) => {
    const raw = (button.form ?? dialogRoot(button))?.querySelector("input[name=value]")?.value ?? "";
    if (String(raw).trim() === "") return null;
    let n = Number(raw);
    if (!Number.isFinite(n)) return null;
    if (Number.isFinite(min)) n = Math.max(min, n);
    if (Number.isFinite(max)) n = Math.min(max, n);
    return n;
  };
  return formDialog({ ...rest, title, icon, content, ok: { ...ok, read } });
}

/**
 * Pick one item from a <select>. With zero or one item it returns immediately without a dialog.
 * ported from LT drop.js:32-42 pickOne, VIT module.js:169-183 (leader picker)
 * @template T
 * @param {T[]} items
 * @param {object} [config]
 * @param {string} [config.title]
 * @param {(item: T) => string} [config.label]     Option text (escaped)
 * @param {(item: T) => string} [config.value]     Written to the option's data-value
 * @param {(item: T) => boolean} [config.selected] Preselected option
 * @param {string} [config.prompt]                 Field label (lang key or text)
 * @param {object} [config.ok]
 * @returns {Promise<T|null>}
 */
export async function pickOne(items, { title, icon, label = defaultLabel, value, selected, prompt = "", ok = {}, ...rest } = {}) {
  const list = Array.from(items ?? []);
  if (list.length <= 1) return list[0] ?? null;
  const options = list
    .map((item, i) => {
      const data = value ? ` data-value="${esc(value(item))}"` : "";
      return `<option value="${i}"${data}${selected?.(item) ? " selected" : ""}>${esc(label(item))}</option>`;
    })
    .join("");
  const content = `<div class="form-group">
      ${prompt ? `<label>${esc(loc(prompt))}</label>` : ""}
      <div class="form-fields"><select name="pick" autofocus>${options}</select></div>
    </div>`;
  const read = (button) => {
    const raw = (button.form ?? dialogRoot(button))?.querySelector("select[name=pick]")?.value;
    return raw === undefined || raw === "" ? null : list[Number(raw)] ?? null;
  };
  return formDialog({
    ...rest,
    title,
    icon,
    content,
    ok: { label: libKey("GATOSLIB.Pick", "Confirm"), ...ok, read },
  });
}

/**
 * Checkbox (multi) or radio (single) list with optional image / icon per row and a live counter when `max`
 * limits the selection (further boxes are disabled once the limit is reached).
 *
 * Row markup: `<label class="gatos-pick-row {rowClass}" data-index data-value><input><img><i><span>label</span>{extra}</label>`
 * — rows without an image use `gatos-check-row` instead of `gatos-pick-row`. Rows get `checked` / `disabled`
 * classes live; the list is `div.gatos-pick-list {listClass}`, the counter `div.gatos-pick-counter`.
 *
 * Result: the checked items in list order (radio → zero or one item), or with `withData` an object
 * `{ items, data }` where `data` is readForm of the other fields in `content` / `after`. An empty `items`
 * returns immediately (`[]`) without a dialog.
 *
 * ported from PP party-panel.js:650-763 (buff / condition pickers), VIT spirit-of-many.js:132-186 (max + counter),
 * VIT collective-panel.js:504-592 (radio), HM module.js:193-231 (keep list)
 * @template T
 * @param {T[]} items
 * @param {object} [config]
 * @param {string} [config.title]
 * @param {string} [config.icon]                 Window icon
 * @param {boolean} [config.multi=true]          Checkboxes (true) or radios (false)
 * @param {number} [config.max]                  Selection limit for checkboxes
 * @param {(item: T) => string} [config.img]     Row image src
 * @param {(item: T) => string} [config.rowIcon] Row icon classes
 * @param {(item: T) => string} [config.label]   Row text (escaped)
 * @param {(item: T) => string} [config.value]   Written to the row's data-value
 * @param {(item: T) => boolean} [config.checked]   Initially checked
 * @param {(item: T) => boolean} [config.disabled]  Row cannot be changed
 * @param {(item: T) => string} [config.extra]   Extra HTML appended inside the row (not escaped)
 * @param {string|((item: T) => string)} [config.rowClass]  Caller's row class(es), e.g. the module's old class
 * @param {string} [config.listClass]            Extra class(es) on the list container
 * @param {string} [config.content]              HTML above the list (hint)
 * @param {string} [config.after]                HTML below the list (extra fields)
 * @param {boolean} [config.withData=false]      Resolve `{ items, data }`
 * @param {object} [config.ok]
 * @param {false|object} [config.cancel]
 * @param {DialogButton[]} [config.buttons]      Extra buttons; without callback they resolve `{ action, data: result }`
 * @param {(event: Event, dialog: DialogV2) => void} [config.render]
 * @returns {Promise<T[]|{items: T[], data: object}|null>}
 */
export async function pickList(
  items,
  {
    title,
    icon,
    multi = true,
    max,
    img,
    rowIcon,
    label = defaultLabel,
    value,
    checked,
    disabled,
    extra,
    rowClass = "",
    listClass = "",
    content = "",
    after = "",
    withData = false,
    ok = {},
    render,
    ...rest
  } = {}
) {
  const list = Array.from(items ?? []);
  if (!list.length) return withData ? { items: [], data: {} } : [];
  const type = multi ? "checkbox" : "radio";
  const limit = multi && Number.isFinite(max) && max > 0 ? Math.floor(max) : null;

  let count = 0;
  const rows = list
    .map((item, i) => {
      let on = !!checked?.(item);
      if (on && !multi && count) on = false; // one radio at most
      if (on) count++;
      const locked = !!disabled?.(item);
      const src = img?.(item);
      const ic = rowIcon?.(item);
      const own = typeof rowClass === "function" ? rowClass(item) : rowClass;
      const cls = [src ? "gatos-pick-row" : "gatos-check-row", ...asClasses(own), on ? "checked" : "", locked ? "disabled" : ""]
        .filter(Boolean)
        .join(" ");
      const data = value ? ` data-value="${esc(value(item))}"` : "";
      return `<label class="${esc(cls)}" data-index="${i}"${data}>
        <input type="${type}" name="${PICK_FIELD}" value="${i}"${on ? " checked" : ""}${locked ? " disabled data-locked=\"true\"" : ""}>
        ${src ? `<img src="${esc(src)}" alt="">` : ""}${ic ? `<i class="${esc(ic)}" inert></i>` : ""}
        <span>${esc(label(item))}</span>${extra ? extra(item) ?? "" : ""}
      </label>`;
    })
    .join("");

  const maxText = limit && game.i18n.has("GATOSLIB.PickMax") ? game.i18n.format("GATOSLIB.PickMax", { max: limit }) : "";
  const counter = limit
    ? `<div class="gatos-pick-counter"${maxText ? ` data-tooltip="${esc(maxText)}"` : ""}>${count} / ${limit}</div>`
    : "";
  const html = `${content}${counter}<div class="${esc(["gatos-pick-list", ...asClasses(listClass)].join(" "))}">${rows}</div>${after}`;

  const live = (event, dialog) => {
    const root = dialog?.element;
    if (!root) return;
    const boxes = Array.from(root.querySelectorAll(`input[name="${PICK_FIELD}"]`));
    const counterEl = root.querySelector(".gatos-pick-counter");
    const sync = () => {
      const n = boxes.filter((b) => b.checked).length;
      for (const b of boxes) {
        const row = b.closest("label");
        row?.classList.toggle("checked", b.checked);
        if (limit && !b.dataset.locked) {
          const full = !b.checked && n >= limit;
          b.disabled = full;
          row?.classList.toggle("disabled", full);
        }
      }
      if (counterEl) counterEl.textContent = `${n} / ${limit}`;
    };
    for (const b of boxes) b.addEventListener("change", sync);
    sync();
  };

  const read = (button) => {
    const form = button.form ?? dialogRoot(button);
    if (!form) return withData ? { items: [], data: {} } : [];
    let picked = Array.from(form.querySelectorAll(`input[name="${PICK_FIELD}"]:checked`))
      .map((input) => list[Number(input.value)])
      .filter((item) => item !== undefined);
    if (limit) picked = picked.slice(0, limit);
    if (!withData) return picked;
    const data = readForm(form);
    delete data[PICK_FIELD];
    return { items: picked, data };
  };

  return formDialog({
    ...rest,
    title,
    icon,
    content: html,
    render: (event, dialog) => {
      live(event, dialog);
      render?.(event, dialog);
    },
    ok: { label: libKey("GATOSLIB.Pick", "Confirm"), ...ok, read },
  });
}

/** Default row / option text: `name` (localized) or the value itself. */
function defaultLabel(item) {
  return loc(item?.name ?? item?.label ?? String(item ?? ""));
}
